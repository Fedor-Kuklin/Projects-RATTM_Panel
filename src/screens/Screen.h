#pragma once

// Базовый класс для всех экранов. Предназначен для постепенного переноса
// глобальных функций экранов в объектно-ориентированную модель.
class Screen {
public:
    virtual ~Screen() {}
    // Вызывается при переходе на экран
    virtual void enter() {}
    // Вызывается при уходе с экрана
    virtual void exit() {}
    // Логика обновления (обработать нажатия, таймеры и т.п.)
    virtual void update() {}
    // Рендер/отрисовка экрана на LCD
    virtual void render() {}
    // Сохранить состояние (например, в регистры/EEPROM)
    virtual void save() {}
    // Загрузить состояние
    virtual void load() {}
    // Обработать нажатие клавиши (по умолчанию ничего не делать)
    virtual void handleKey(char key) {}
};
